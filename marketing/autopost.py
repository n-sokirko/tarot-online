def _load_state() -> dict:
    """Читает состояние ротации. Поддерживает миграцию со старого .post_index."""
    try:
        with open(STATE_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
            return {
                "n": int(data.get("n", 0)),
                "fact": int(data.get("fact", 0)),
                "promo": int(data.get("promo", 0)),
            }
    except (FileNotFoundError, ValueError, json.JSONDecodeError):
        pass
    # Бэк-совместимость: подхватываем старый .post_index как стартовый промо-индекс.
    promo_start = 0
    try:
        with open(LEGACY_INDEX_FILE, "r", encoding="utf-8") as f:
            promo_start = int(f.read().strip())
    except (FileNotFoundError, ValueError):
        pass
    return {"n": 0, "fact": 0, "promo": promo_start}


def _save_state(state: dict) -> None:
    try:
        with open(STATE_FILE, "w", encoding="utf-8") as f:
            json.dump(state, f, ensure_ascii=False)
    except OSError as e:
        logging.error(f"Не смог сохранить состояние ротации: {e}")


def pick_post(state: dict) -> tuple[str, str, dict]:
    """
    Возвращает (тип, текст_поста, новое_состояние).
    Ротация 2 факта : 1 реклама — каждый третий пост рекламный.
    """
    n = state["n"]
    if n % 3 == 2:
        idx = state["promo"] % len(PROMO)
        post = PROMO[idx]
        kind = f"PROMO #{idx + 1}/{len(PROMO)}"
        state = {**state, "n": n + 1, "promo": state["promo"] + 1}
    else:
        idx = state["fact"] % len(FACTS)
        post = FACTS[idx]
        kind = f"FACT #{idx + 1}/{len(FACTS)}"
        state = {**state, "n": n + 1, "fact": state["fact"] + 1}
    return kind, post, state


def send_message(text: str) -> bool:
    """Отправляет сообщение в канал через Bot API."""
    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    payload = {
        "chat_id": CHANNEL_ID,
        "text": text,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }
    try:
        r = requests.post(url, json=payload, timeout=15, proxies={"http": None, "https": None})
        r.raise_for_status()
        result = r.json()
        if result.get("ok"):
            logging.info(f"✅ Пост отправлен в {CHANNEL_ID}")
            return True
        logging.error(f"Telegram API error: {result}")
        return False
    except Exception as e:  # noqa: BLE001 — best-effort
        logging.error(f"Ошибка отправки: {e}")
        return False


def main():
    dry_run = "--dry-run" in sys.argv

    if not BOT_TOKEN and not dry_run:
        logging.error("TELEGRAM_BOT_TOKEN не задан в .env!")
        sys.exit(1)

    state = _load_state()
    kind, post, new_state = pick_post(state)
    logging.info(f"Очередной пост: {kind}")

    if dry_run:
        print(f"\n----- DRY RUN: {kind} -> {CHANNEL_ID} -----\n{post}\n----- (не отправлено) -----\n")
        print(f"Состояние стало бы: {new_state}")
        sys.exit(0)

    success = send_message(post)
    if success:
        _save_state(new_state)
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
